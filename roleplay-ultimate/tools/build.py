SCHEMA = {0x0000:0,0x0001:1,0x0002:1,0x0006:2,0x000A:2,0x000E:2,
 0x0019:2,0x001D:2,0x0039:2,0x003B:2,0x004D:1,0x0051:0,0x005A:2,
 0x0062:2,0x0085:2,0x00D6:1,0x0050:1,0x0109:2,0x010B:2,
 0x0256:1,0x0A9A:3,0x0A9B:1,0x0A9C:2,0x0A9D:3,0x0A9E:3,
 0x0AAB:1,0x0AB0:1,0x0AD1:-1}
def V(n): return ('v',n)
def L(s): return ('l',s)
def encode_arg(a, labels=None):
 if isinstance(a,tuple):
  kind,val=a
  if kind=='v':
   if not 0 <= val <= 33: raise ValueError('Invalid local')
   return b'\x03'+struct.pack('<H',val)
  if kind=='l':
   offset = labels[val] if labels is not None else 1
   if offset <= 0: raise ValueError('CLEO label must be at a negative offset')
   return b'\x01'+struct.pack('<i',-offset)
 if isinstance(a,int): return b'\x01'+struct.pack('<i',a)
 if isinstance(a,str):
  b=a.encode('ascii')
  if len(b)>255: raise ValueError('String too long')
  return b'\x0e'+bytes([len(b)])+b
 raise ValueError(a)
def assemble(code):
 labels={}; pos=0
 for row in code:
  if isinstance(row,str):
   if row in labels: raise ValueError('Duplicate label')
   labels[row]=pos; continue
  op,*args=row; arity=SCHEMA[op&0x7fff]
  if arity>=0 and len(args)!=arity: raise ValueError(row)
  if arity<0 and len(args)<2: raise ValueError(row)
  pos+=2+sum(len(encode_arg(a)) for a in args)+(arity<0)
 out=bytearray()
 for row in code:
  if isinstance(row,str): continue
  op,*args=row; out+=struct.pack('<H',op)
  for a in args: out+=encode_arg(a,labels)
  if SCHEMA[op&0x7fff]<0: out+=b'\0'
 return bytes(out),labels
class Program:
 def __init__(self): self.code=[]; self.serial=0
 def emit(self,op,*args): self.code.append((op,*args))
 def label(self,name): self.code.append(name)
 def jump(self,name): self.emit(2,L(name))
 def call(self,name): self.emit(0x50,L(name))
 def ret(self): self.emit(0x51)
 def set(self,n,value): self.emit(0x0085 if isinstance(value,tuple) else 6,V(n),value)
 def add(self,n,value): self.emit(0x005A if isinstance(value,tuple) else 0xA,V(n),value)
 def sub(self,n,value): self.emit(0x0062 if isinstance(value,tuple) else 0xE,V(n),value)
 def when(self,op,args,body):
  self.serial+=1; end=f'IF_END_{self.serial}'
  self.emit(0xD6,0); self.emit(op,*args); self.emit(0x4D,L(end)); body(); self.label(end)
 def require(self,op,args,end):
  self.emit(0xD6,0); self.emit(op,*args); self.emit(0x4D,L(end))
 def text(self,s,*args): self.emit(0xAD1,s,2600,*args)
 def key(self,key,body):
  def run(): body(); self.set(28,key); self.call('RELEASE'); self.jump('LOOP')
  self.when(0xAB0,[key],run)
 def source(self):
  def arg(a):
   if isinstance(a,tuple): return f'{a[1]}@' if a[0]=='v' else '@'+a[1]
   if isinstance(a,str): return json.dumps(a)
   return str(a)
  lines=['{$CLEO .cs}','// GTA SA RP Ultimate 0.1.0-alpha — experimental technical core.',
   '// Generated by tools/build.py; all locals private; no engine memory patches.',
   '// 0 active; 1 menu; 2 cash; 3 bank; 4 ID; 5 work card; 6 account;',
   '// 7 generation; 8 current journal slot; 9..28 IO/scratch; 32/33 timers.']
  for row in self.code:
   lines.append(':'+row if isinstance(row,str) else f'{row[0]:04X}: '+' '.join(map(arg,row[1:])))
  return '\n'.join(lines)+'\n'
